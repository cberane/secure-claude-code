#!/usr/bin/env bash
# Merge a PROJECT's egress additions into egress/allowlist.project.txt,
# which the egress-proxy image bakes in as a fourth merge source (see
# egress/Dockerfile). The project file lives in the repo (mounted at
# /workspace/egress/allowlist.txt) so the per-domain "# why" documentation
# travels with the project and survives workspace loss — unlike the
# machine-local workspace fragment (docs/workspaces.md).
#
# The generated copy stays machine-local build material: gitignored, never
# hand-edited, and REWRITTEN ONLY WHEN ITS CONTENT CHANGES (stable mtime
# keeps the docker layer cache warm when this runs on every make).
#
# Policy: git hosts may NEVER enter through this or any other fragment —
# the only git-host access path is the workspace's generated scope file
# (egress/allowlist.git-scope.txt). This script enforces it for the
# project source; EGRESS/git-scope hygiene is asserted by doctor.
#
# Runs unconditionally as a make prerequisite (a file rule with no
# prerequisites would fire once and go stale — Makefile hazard).
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
target="$repo_root/egress/allowlist.project.txt"

project_dir="${PROJECTS_DIR:-}"
if [ -z "$project_dir" ] && [ -f "$repo_root/.env" ]; then
    project_dir="$(sed -n 's/^PROJECTS_DIR=//p' "$repo_root/.env" | tail -1)"
fi

stub='# Per-PROJECT egress additions — generated by scripts/merge-project-allowlist.sh.
# Do not edit: author the domains (with a "# why" comment each) in
# <project>/egress/allowlist.txt (mounted at /workspace/egress/).'

# Write atomically, but ONLY when content differs: this script runs on every
# make invocation, and a stable mtime keeps the egress-proxy layer cache warm.
write_target() {
    local tmp
    tmp="$(mktemp "$target.tmp.XXXXXX")"
    {
        printf '%s\n' "$stub"
        [ -n "${merged:-}" ] && printf '%s\n' "$merged"
    } > "$tmp"
    chmod 644 "$tmp"
    if [ -f "$target" ] && cmp -s "$tmp" "$target"; then
        rm -f "$tmp"
    else
        mv "$tmp" "$target"
    fi
}

# No project configured (fresh clone, no .env yet): leave the stub.
if [ -z "$project_dir" ]; then
    write_target
    exit 0
fi

source_file="$project_dir/egress/allowlist.txt"

if [ ! -f "$source_file" ]; then
    write_target
    exit 0
fi

# Apex git hosts are forbidden in the merged sources — same rule the docs
# state for the machine-global list. Exact-line matches only: toolchain
# fragments legitimately carry READ endpoints like api.github.com.
if grep -ihE '^[[:space:]]*(github\.com|gitlab\.com|bitbucket\.org)([[:space:]]|#|$)' \
        "$source_file" >/dev/null; then
    echo "REFUSED: $source_file contains a git remote host (github.com, gitlab.com, bitbucket.org)." >&2
    echo "Git hosts only reach the proxy through the per-workspace GitHub scope file —" >&2
    echo "declare GITHUB_* in .secure-container/workspace.env instead (docs/github.md)." >&2
    exit 1
fi

merged="$(grep -v '^[[:space:]]*#' "$source_file" | sed '/^[[:space:]]*$/d' | sort -u || true)"
write_target
