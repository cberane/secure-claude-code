#!/usr/bin/env bash
# workspace.sh — named workspace profiles compiled into the repo's .env.
#
# A workspace is one .env-worth of per-project settings (PROJECTS_DIR,
# TOOLCHAINS, limits, EGRESS posture) stored as workspaces/<name>.env.
# Switching regenerates .env from workspaces/common.env + <name>.env
# (workspace wins on duplicate keys) and applies the delta with the
# cheapest sufficient action: nothing, reload-egress, restart, or
# build + restart. .env becomes a GENERATED artifact — a checksum header
# detects manual edits so they are never silently clobbered.
#
#   scripts/workspace.sh list          — definitions, active one marked
#   scripts/workspace.sh current       — active workspace + sync status
#   scripts/workspace.sh new <name>    — create a definition (seeded from .env)
#   scripts/workspace.sh switch <name> — regenerate .env and apply
#
# EGRESS=learning in a definition routes through the existing `make learn`
# / `make learn-off` plumbing — open egress keeps its coupling (signing
# key removed, doctor red). This script never implements a separate,
# weaker open mode (DECISIONS.md).
#
# Escape hatches for automation: FORCE=1 overrides the manual-edit guard
# on switch, WS_ACK=yes skips the kill-running-session confirmation.
set -euo pipefail

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo_root="$(cd "$script_dir/.." && pwd)"
cd "$repo_root"

WS_DIR=workspaces
ENV_FILE=.env
ACTIVE_MARKER=.workspace
FRAG_TARGET=egress/allowlist.workspace.txt

die() { printf 'workspace: %s\n' "$*" >&2; exit 1; }

# Last assignment of a key in an env file, compose-style quote stripping.
env_get() { # env_get <file> <key>
    [ -f "$1" ] || return 0
    sed -n "s/^$2=//p" "$1" | tail -1 \
        | sed -e 's/^"\(.*\)"$/\1/' -e "s/^'\(.*\)'$/\1/"
}

# Content below the generated header (or the whole file if not generated).
payload() { # payload <file>
    if grep -q '^# sha256:' "$1"; then
        sed '1,/^# sha256:/d' "$1"
    else
        cat "$1"
    fi
}

sha_of() { sha256sum | cut -d' ' -f1; }

# KEY=VALUE lines from the given files; later files win, first-seen order.
merge() {
    awk -F= '/^[A-Za-z_][A-Za-z_0-9]*=/ {
        key = $1
        if (!(key in val)) order[++n] = key
        val[key] = $0
    } END { for (i = 1; i <= n; i++) print val[order[i]] }' "$@"
}

# The merged payload a workspace would produce right now.
merged_for() { # merged_for <name>
    if [ -f "$WS_DIR/common.env" ]; then
        merge "$WS_DIR/common.env" "$WS_DIR/$1.env"
    else
        merge "$WS_DIR/$1.env"
    fi
}

# The egress fragment content a workspace prescribes (default: empty stub).
frag_for() { # frag_for <name>
    if [ -f "$WS_DIR/$1.allowlist.txt" ]; then
        cat "$WS_DIR/$1.allowlist.txt"
    else
        printf '# Per-workspace egress additions — generated by scripts/workspace.sh.\n'
        printf '# Do not edit: put domains into workspaces/<name>.allowlist.txt instead.\n'
    fi
}

engine() {
    local e
    e="$(env_get "$ENV_FILE" ENGINE)"
    printf '%s' "${e:-docker}"
}

########################################################################
# list
########################################################################
cmd_list() {
    local active="" f name mark tc eg pd
    [ -f "$ACTIVE_MARKER" ] && active="$(cat "$ACTIVE_MARKER")"
    if ! ls "$WS_DIR"/*.env >/dev/null 2>&1; then
        echo "No workspace definitions yet — create one with: make new-workspace NAME=<name>"
        return 0
    fi
    for f in "$WS_DIR"/*.env; do
        name="$(basename "$f" .env)"
        [ "$name" = common ] && continue
        mark=" "
        [ "$name" = "$active" ] && mark="*"
        tc="$(env_get "$f" TOOLCHAINS)"
        eg="$(env_get "$f" EGRESS)"
        pd="$(env_get "$f" PROJECTS_DIR)"
        printf '%s %-20s toolchains=%-18s egress=%-9s %s\n' \
            "$mark" "$name" "${tc:-<none>}" "${eg:-allowlist}" "$pd"
    done
    [ -n "$active" ] && echo "(* = active; switch with: make workspace NAME=<name>)"
}

########################################################################
# current
########################################################################
cmd_current() {
    if [ ! -f "$ACTIVE_MARKER" ]; then
        echo "No active workspace — .env is managed by hand (legacy mode)."
        echo "Adopt it with: make new-workspace NAME=<name> && make workspace NAME=<name>"
        return 0
    fi
    local name stored actual
    name="$(cat "$ACTIVE_MARKER")"
    echo "Active workspace: $name"
    [ -f "$WS_DIR/$name.env" ] || { echo "WARNING: workspaces/$name.env is missing."; return 1; }
    if [ ! -f "$ENV_FILE" ] || ! grep -q '^# workspace:' "$ENV_FILE"; then
        echo "WARNING: .env is not workspace-generated — rerun: make workspace NAME=$name"
        return 1
    fi
    stored="$(sed -n 's/^# sha256: //p' "$ENV_FILE" | head -1)"
    actual="$(payload "$ENV_FILE" | sha_of)"
    if [ "$stored" != "$actual" ]; then
        echo "WARNING: .env was edited by hand since generation — fold the edit into"
        echo "         workspaces/$name.env, then rerun: make workspace NAME=$name"
        return 1
    fi
    if [ "$(merged_for "$name")" != "$(payload "$ENV_FILE")" ]; then
        echo "Definition edited since last switch — apply with: make workspace NAME=$name"
    else
        echo ".env is in sync with the definition."
    fi
}

########################################################################
# new <name>
########################################################################
cmd_new() {
    local name="${1:-}"
    [ -n "$name" ] || die "usage: scripts/workspace.sh new <name>  (or: make new-workspace NAME=<name>)"
    printf '%s' "$name" | grep -Eq '^[a-z0-9][a-z0-9-]*$' \
        || die "name must be kebab-case: lowercase letters, digits, dashes ('$name')"
    [ "$name" = common ] && die "'common' is reserved for workspaces/common.env"
    local ws="$WS_DIR/$name.env"
    [ -f "$ws" ] && die "$ws already exists — edit it, or pick another name"
    mkdir -p "$WS_DIR"

    # Shared settings live in common.env, written ONCE — seeded from the
    # current .env when there is one (smooth first-time adoption).
    if [ ! -f "$WS_DIR/common.env" ]; then
        {
            echo "# Shared across ALL workspaces — merged first; <name>.env overrides."
            echo "# Same format rules as .env: no '#' or '\$' inside values."
            echo "ENGINE=$(v="$(env_get "$ENV_FILE" ENGINE)"; printf '%s' "${v:-docker}")"
            echo "UID=$(v="$(env_get "$ENV_FILE" UID)"; printf '%s' "${v:-$(id -u)}")"
            echo "GID=$(v="$(env_get "$ENV_FILE" GID)"; printf '%s' "${v:-$(id -g)}")"
            echo "GIT_AUTHOR_NAME=$(env_get "$ENV_FILE" GIT_AUTHOR_NAME)"
            echo "GIT_AUTHOR_EMAIL=$(env_get "$ENV_FILE" GIT_AUTHOR_EMAIL)"
            echo "ANTHROPIC_API_KEY=$(env_get "$ENV_FILE" ANTHROPIC_API_KEY)"
        } > "$WS_DIR/common.env"
        echo "Created $WS_DIR/common.env (shared identity/engine — edit once, applies everywhere)."
    fi

    local seed_pd seed_tc
    seed_pd="$(env_get "$ENV_FILE" PROJECTS_DIR)"
    seed_tc="$(env_get "$ENV_FILE" TOOLCHAINS)"
    cat > "$ws" <<EOF
# Workspace '$name' — applied with: make workspace NAME=$name
# Merged over workspaces/common.env (this file wins on duplicate keys).

# REQUIRED: absolute host path mounted at /workspace (the only writable bind mount).
PROJECTS_DIR=${seed_pd:-/home/you/projects/my-project}

# Comma list of toolchains: php, python, docker (empty = slim runtime).
# Drives BOTH the image contents and the egress allowlist fragments.
TOOLCHAINS=${seed_tc}

# Egress posture:
#   allowlist  — hardened default (curated domains only)
#   learning   — OPEN egress via \`make learn\`: everything logged, signing
#                key removed, doctor red. For research sessions only; pairs
#                best with TOOLCHAINS= (empty).
EGRESS=allowlist

# Optional overrides (defaults come from common.env / compose):
#ANTHROPIC_MODEL=
#MEM_LIMIT=4g
#DIND_MEM_LIMIT=4g
#CPUS=2
#PIDS_LIMIT=512
#NOFILE=4096
#TMP_SIZE=512m
#CERT_DAYS=3

# Extra egress domains for THIS workspace: one squid domain per line in
#   workspaces/$name.allowlist.txt
# (baked into the proxy on switch; 'make denied' shows what got blocked).
EOF
    echo "Created $ws — review/edit it, then activate with:"
    echo "    make workspace NAME=$name"
}

########################################################################
# switch <name>
########################################################################
cmd_switch() {
    local name="${1:-}"
    [ -n "$name" ] || die "usage: scripts/workspace.sh switch <name>  (or: make workspace NAME=<name>)"
    local ws="$WS_DIR/$name.env"
    if [ ! -f "$ws" ]; then
        echo "workspace: no definition $ws" >&2
        cmd_list >&2
        exit 1
    fi

    # --- old state, for the cheapest-apply decision -----------------------
    local old_tc="" old_pd="" old_dind_mem="" was_learning=0 had_env=0
    if [ -f "$ENV_FILE" ]; then
        had_env=1
        old_tc="$(env_get "$ENV_FILE" TOOLCHAINS)"
        old_pd="$(env_get "$ENV_FILE" PROJECTS_DIR)"
        old_dind_mem="$(env_get "$ENV_FILE" DIND_MEM_LIMIT)"
    fi
    [ -e .learning-mode ] && was_learning=1

    # --- guard: never clobber a hand-edited .env --------------------------
    if [ "$had_env" = 1 ]; then
        if grep -q '^# workspace:' "$ENV_FILE"; then
            local stored actual
            stored="$(sed -n 's/^# sha256: //p' "$ENV_FILE" | head -1)"
            actual="$(payload "$ENV_FILE" | sha_of)"
            if [ "$stored" != "$actual" ] && [ "${FORCE:-0}" != 1 ]; then
                die ".env was edited by hand since it was generated.
Fold the edit into $WS_DIR/$(sed -n 's/^# workspace: //p' "$ENV_FILE" | head -1).env (or common.env),
or override once with: FORCE=1 make workspace NAME=$name"
            fi
        else
            # Legacy hand-written .env: preserve it, then take over.
            local backup=.env.pre-workspaces
            [ -e "$backup" ] && backup=".env.pre-workspaces.$$"
            cp "$ENV_FILE" "$backup"
            echo "note: existing hand-written .env preserved as $backup"
        fi
    fi

    # --- merge + validate the new configuration ---------------------------
    local merged new_tc new_pd new_dind_mem new_egress t
    merged="$(merged_for "$name")"
    local tmp
    tmp="$(mktemp)"
    printf '%s\n' "$merged" > "$tmp"
    new_tc="$(env_get "$tmp" TOOLCHAINS)"
    new_pd="$(env_get "$tmp" PROJECTS_DIR)"
    new_dind_mem="$(env_get "$tmp" DIND_MEM_LIMIT)"
    new_egress="$(env_get "$tmp" EGRESS)"
    rm -f "$tmp"
    new_egress="${new_egress:-allowlist}"

    [ -n "$new_pd" ] || die "PROJECTS_DIR is not set in $ws (or common.env)"
    [ -d "$new_pd" ] || die "PROJECTS_DIR '$new_pd' does not exist on the host"
    case "$new_egress" in
        allowlist|learning) ;;
        *) die "EGRESS must be 'allowlist' or 'learning' (got '$new_egress')" ;;
    esac
    for t in $(printf '%s' "$new_tc" | tr ',' ' '); do
        [ -f "egress/allowlist.d/$t.txt" ] \
            || die "unknown toolchain '$t' in $ws (no egress/allowlist.d/$t.txt)"
    done
    if printf '%s\n' "$merged" | grep -q '[#$]'; then
        echo "warning: a value contains '#' or '\$' — Make's .env include mangles both (see Makefile)." >&2
    fi

    # --- what does the delta require? -------------------------------------
    local build_needed=0 restart_needed=0 frag_changed=0
    local leaving_learning=0 entering_learning=0
    [ "$new_tc" != "$old_tc" ] && build_needed=1
    if [ "$build_needed" = 1 ] || [ "$new_pd" != "$old_pd" ] || [ "$new_dind_mem" != "$old_dind_mem" ]; then
        restart_needed=1
    fi
    if [ "$was_learning" = 1 ] && [ "$new_egress" != learning ]; then leaving_learning=1; fi
    if [ "$was_learning" = 0 ] && [ "$new_egress" = learning ]; then entering_learning=1; fi
    local new_frag
    new_frag="$(frag_for "$name")"
    if [ ! -f "$FRAG_TARGET" ] || [ "$new_frag" != "$(cat "$FRAG_TARGET")" ]; then
        frag_changed=1
    fi

    # --- confirm before killing a running session -------------------------
    local eng
    eng="$(engine)"
    if [ "$restart_needed" = 1 ] && [ "${WS_ACK:-}" != yes ] \
        && [ -n "$($eng ps -q -f name='^claude-session$' 2>/dev/null)" ]; then
        echo "A session (claude-session) is RUNNING — the switch needs a restart, which kills it"
        case ",$old_tc," in *,docker,*) echo "and every container nested inside dind (databases, mailpit, ...)." ;; esac
        printf 'Continue? [y/N] '
        local answer=""
        [ -t 0 ] && read -r answer
        case "$answer" in y|Y|yes) ;; *) die "aborted — close the session first, or rerun with WS_ACK=yes" ;; esac
    fi

    # --- write the generated .env + state ---------------------------------
    local sha
    sha="$(printf '%s\n' "$merged" | sha_of)"
    {
        echo "# GENERATED by scripts/workspace.sh from $ws — do not edit."
        echo "# Edit $ws (or workspaces/common.env), then rerun: make workspace NAME=$name"
        echo "# workspace: $name"
        echo "# sha256: $sha"
        printf '%s\n' "$merged"
    } > "$ENV_FILE.tmp"
    mv "$ENV_FILE.tmp" "$ENV_FILE"
    printf '%s\n' "$name" > "$ACTIVE_MARKER"
    printf '%s\n' "$new_frag" > "$FRAG_TARGET"

    # --- apply ------------------------------------------------------------
    # Order matters: learn-off first (rebuilds the proxy ENFORCING, with the
    # new .env), then image builds, then restart, then learn last (its
    # confirm gate must see the new TOOLCHAINS).
    local running=""
    running="$($eng ps -q --filter label=com.docker.compose.project=claude-sandbox 2>/dev/null | head -1)"

    if [ "$leaving_learning" = 1 ]; then
        echo "--- leaving learning mode (make learn-off) ---"
        make learn-off
    fi
    if [ "$build_needed" = 1 ]; then
        echo "--- toolchains changed ('$old_tc' -> '$new_tc'): make build ---"
        make build
    elif [ "$frag_changed" = 1 ] && [ "$leaving_learning" = 0 ] && [ "$entering_learning" = 0 ]; then
        echo "--- workspace allowlist fragment changed: make reload-egress ---"
        make reload-egress
    fi
    if [ "$restart_needed" = 1 ] && [ -n "$running" ]; then
        echo "--- applying to running sandbox: make restart ---"
        make restart
    fi
    if [ "$entering_learning" = 1 ]; then
        echo "--- workspace declares EGRESS=learning: make learn ---"
        make learn
    fi

    # --- summary ----------------------------------------------------------
    echo
    echo "Workspace '$name' is active."
    echo "    PROJECTS_DIR = $new_pd"
    echo "    TOOLCHAINS   = ${new_tc:-<none>}"
    echo "    EGRESS       = $new_egress"
    if [ "$restart_needed" = 1 ] && [ -z "$running" ]; then
        echo "Nothing was running — start with: make claude   (or make yolo / make shell)"
    fi
    if [ "$build_needed" = 0 ] && [ "$restart_needed" = 0 ]; then
        echo "No rebuild/restart needed — value changes apply to new sessions automatically."
    fi
    [ "$new_egress" = learning ] || echo "Verify the posture with: make doctor"
}

########################################################################
# dispatch
########################################################################
case "${1:-}" in
    list)    cmd_list ;;
    current) cmd_current ;;
    new)     shift; cmd_new "$@" ;;
    switch)  shift; cmd_switch "$@" ;;
    *)
        echo "usage: scripts/workspace.sh {list|current|new <name>|switch <name>}" >&2
        exit 2
        ;;
esac
