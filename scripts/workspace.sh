#!/usr/bin/env bash
# workspace.sh — named workspace profiles compiled into the repo's .env.
#
# A workspace is one .env-worth of per-project settings (PROJECTS_DIR,
# TOOLCHAINS, limits, EGRESS posture). Two anchoring models exist:
#
#   * repo-anchored (preferred): the project repo carries a versioned
#     .secure-container/ folder with the profile (workspace.env: TOOLCHAINS,
#     EGRESS, GITHUB_* scope) and the per-project egress allowlist
#     (.secure-container/egress/allowlist.txt, "# why"-documented). The
#     machine-local workspaces/<name>.env then only holds a reference
#     (SECURE_PROJECT_PATH=<abs host path>) plus machine-only overrides.
#     Created with: make add-workspace PROJECT=~/projects/<name>
#   * machine-local (legacy): the whole definition lives in
#     workspaces/<name>.env as before. Created with: make new-workspace.
#
# The merge chain is: workspaces/common.env →
# <SECURE_PROJECT_PATH>/.secure-container/workspace.env → workspaces/<name>.env
# (machine overrides win over the profile, but never over secrets.env last). Switching regenerates .env from that chain and applies
# the delta with the cheapest sufficient action: nothing, reload-egress,
# restart, or build + restart. .env is a GENERATED artifact — a checksum
# header detects manual edits so they are never silently clobbered.
#
#   scripts/workspace.sh list              — definitions, active one marked
#   scripts/workspace.sh current          — active workspace + sync status
#   scripts/workspace.sh new <name>       — machine-local definition
#   scripts/workspace.sh add <path> [nm]  — register a repo-anchored one
#   scripts/workspace.sh switch <name>    — regenerate .env and apply
#
# EGRESS=learning in a definition routes through the existing `make learn`
# / `make learn-off` plumbing — open egress keeps its coupling (signing
# key removed, doctor red). This script never implements a separate,
# weaker open mode (DECISIONS.md). Workspaces carrying a GITHUB scope may
# NEVER enter learning mode (the open proxy would pair with a mounted
# token) — refused here during validation and at the make learn gate.
#
# API keys and other secrets live in gitignored workspaces/secrets.env
# (merged LAST, so it wins over every definition). The generated .env
# inherits them, compose passes them into the container — and they survive
# every switch/edit of the definition files. Never put keys into common.env,
# <name>.env or .secure-container/workspace.env — the latter is COMMITTED.
#
# Escape hatches for automation: FORCE=1 overrides the manual-edit guard
# on switch, WS_ACK=yes skips the kill-running-session confirmation.
set -euo pipefail

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo_root="$(cd "$script_dir/.." && pwd)"
cd "$repo_root"

WS_DIR=workspaces
ENV_FILE=.env
ACTIVE_MARKER=.workspace
FRAG_TARGET=egress/allowlist.workspace.txt
SCOPE_TARGET=egress/allowlist.git-scope.txt
SECRETS_FILE=$WS_DIR/secrets.env

# Git-host domains the GitHub scope opens (docs/github.md). Fixed set:
# nothing user-configurable goes into the scope — the mint step narrows the
# TOKEN instead, this file only opens the transport. No leading dot on
# github.com, and never alongside a `.github.com` wildcard in the same ACL
# file (squid subdomain-of-wildcard config error).
SCOPE_DOMAINS=(
    '# Github egress scope for the active workspace — generated by'
    '# scripts/workspace.sh from .secure-container GITHUB_* settings.'
    '# Do not edit: edit the .secure-container scope and re-switch.'
    'github.com'
    'api.github.com'
    'uploads.github.com'
    '.githubusercontent.com'
)

die() { printf 'workspace: %s\n' "$*" >&2; exit 1; }

# Last assignment of a key in an env file, compose-style quote stripping.
env_get() { # env_get <file> <key>
    [ -f "$1" ] || return 0
    sed -n "s/^$2=//p" "$1" | tail -1 \
        | sed -e 's/^"\(.*\)"$/\1/' -e "s/^'\(.*\)'$/\1/"
}

# Content below the generated header (or the whole file if not generated).
payload() { # payload <file>
    if grep -q '^# sha256:' "$1"; then
        sed '1,/^# sha256:/d' "$1"
    else
        cat "$1"
    fi
}

sha_of() { sha256sum | cut -d' ' -f1; }

# KEY=VALUE lines from the given files; later files win, first-seen order.
merge() {
    awk -F= '/^[A-Za-z_][A-Za-z_0-9]*=/ {
        key = $1
        if (!(key in val)) order[++n] = key
        val[key] = $0
    } END { for (i = 1; i <= n; i++) print val[order[i]] }' "$@"
}

# The repo-anchored profile a workspace reference points at.
# SECURE_PROJECT_PATH=<abs host path> in workspaces/<name>.env; the profile
# lives at <path>/.secure-container/workspace.env. Empty when unset/missing.
repo_profile_for() { # repo_profile_for <name>
    local sp
    sp="$(env_get "$WS_DIR/$1.env" SECURE_PROJECT_PATH)"
    if [ -n "$sp" ] && [ -f "$sp/.secure-container/workspace.env" ]; then
        printf '%s\n' "$sp/.secure-container/workspace.env"
    fi
}

# The merged payload a workspace would produce right now. Chain:
# common.env → repo-anchored profile (if registered as one) → <name>.env →
# secrets.env (gitignored, wins over everything). The repo profile carries
# project truth; the machine-local <name>.env holds the SECURE_PROJECT_PATH
# reference plus allowed MACHINE-only overrides (e.g. memory limits) — it may
# deviate from the profile locally, but secrets always win. For repo-anchored
# workspaces with no explicit PROJECTS_DIR one is derived from
# SECURE_PROJECT_PATH — the project checkout IS the mounted /workspace.
merged_for() { # merged_for <name>
    local files=() sp
    [ -f "$WS_DIR/common.env" ] && files+=("$WS_DIR/common.env")
    local repo_profile
    repo_profile="$(repo_profile_for "$1")"
    [ -n "$repo_profile" ] && files+=("$repo_profile")
    files+=("$WS_DIR/$1.env")
    [ -f "$SECRETS_FILE" ] && files+=("$SECRETS_FILE")
    local merged
    merged="$(merge "${files[@]}")"
    sp="$(env_get "$WS_DIR/$1.env" SECURE_PROJECT_PATH)"
    if [ -n "$sp" ] && ! printf '%s\n' "$merged" | grep -q '^PROJECTS_DIR='; then
        merged="$(printf '%s\nPROJECTS_DIR=%s\n' "$merged" "$sp")"
    fi
    printf '%s\n' "$merged"
}

# True when the merged workspace config declares a GITHUB scope.
scope_active() { # scope_active <merged-payload-file-or-""> <name>
    # Decided on the merged payload: every GITHUB_* field must be present
    # together — half-configured scopes die during switch validation.
    local f="$1"
    [ -n "$(env_get "$f" GITHUB_APP_ID)" ] \
        && [ -n "$(env_get "$f" GITHUB_INSTALLATION_ID)" ] \
        && [ -n "$(env_get "$f" GITHUB_REPO)" ]
}

# The git-host scope content a workspace prescribes (stub when no scope).
git_scope_for() { # git_scope_for <payload-file>
    if scope_active "$1"; then
        printf '%s\n' "${SCOPE_DOMAINS[@]}"
    else
        printf '%s\n' '# Git-host egress scope — generated by scripts/workspace.sh.'
        printf '%s\n' '# Do not edit: declare GITHUB_* in .secure-container/workspace.env instead.'
    fi
}

# The egress fragment content a workspace prescribes (default: empty stub).
frag_for() { # frag_for <name>
    if [ -f "$WS_DIR/$1.allowlist.txt" ]; then
        cat "$WS_DIR/$1.allowlist.txt"
    else
        printf '# Per-workspace egress additions — generated by scripts/workspace.sh.\n'
        printf '# Do not edit: put domains into workspaces/<name>.allowlist.txt instead.\n'
    fi
}

engine() {
    local e
    e="$(env_get "$ENV_FILE" ENGINE)"
    printf '%s' "${e:-docker}"
}

########################################################################
# list
########################################################################
cmd_list() {
    local active="" f name mark tc eg pd sp
    [ -f "$ACTIVE_MARKER" ] && active="$(cat "$ACTIVE_MARKER")"
    if ! ls "$WS_DIR"/*.env >/dev/null 2>&1; then
        echo "No workspace definitions yet — for a project repo: make add-workspace PROJECT=~/projects/<name>"
        echo "                                (machine-local, no repo: make new-workspace NAME=<name>)"
        return 0
    fi
    for f in "$WS_DIR"/*.env; do
        name="$(basename "$f" .env)"
        if [ "$name" = common ] || [ "$name" = secrets ]; then continue; fi
        mark=" "
        [ "$name" = "$active" ] && mark="*"
        tc="$(env_get "$f" TOOLCHAINS)"
        eg="$(env_get "$f" EGRESS)"
        sp="$(env_get "$f" SECURE_PROJECT_PATH)"
        pd="$(env_get "$f" PROJECTS_DIR)"
        [ -n "$sp" ] && pd="$sp (repo-anchored)"
        printf '%s %-20s toolchains=%-18s egress=%-9s %s\n' \
            "$mark" "$name" "${tc:-<repo profile>}" "${eg:-<repo profile>}" "$pd"
    done
    [ -n "$active" ] && echo "(* = active; switch with: make workspace NAME=<name>)"
}

########################################################################
# current
########################################################################
cmd_current() {
    if [ ! -f "$ACTIVE_MARKER" ]; then
        echo "No active workspace — .env is managed by hand (legacy mode)."
        echo "Adopt it with: make new-workspace NAME=<name> && make workspace NAME=<name>"
        return 0
    fi
    local name stored actual
    name="$(cat "$ACTIVE_MARKER")"
    echo "Active workspace: $name"
    [ -f "$WS_DIR/$name.env" ] || { echo "WARNING: workspaces/$name.env is missing."; return 1; }
    if [ ! -f "$ENV_FILE" ] || ! grep -q '^# workspace:' "$ENV_FILE"; then
        echo "WARNING: .env is not workspace-generated — rerun: make workspace NAME=$name"
        return 1
    fi
    stored="$(sed -n 's/^# sha256: //p' "$ENV_FILE" | head -1)"
    actual="$(payload "$ENV_FILE" | sha_of)"
    if [ "$stored" != "$actual" ]; then
        echo "WARNING: .env was edited by hand since generation — fold the edit into"
        echo "         workspaces/$name.env, then rerun: make workspace NAME=$name"
        return 1
    fi
    if [ "$(merged_for "$name")" != "$(payload "$ENV_FILE")" ]; then
        echo "Definition or project config (.secure-container/) changed since last"
        echo "switch — apply with: make workspace NAME=$name"
    else
        echo ".env is in sync with the definition."
    fi
}

########################################################################
# new <name>
########################################################################
cmd_new() {
    local name="${1:-}"
    [ -n "$name" ] || die "usage: scripts/workspace.sh new <name>  (or: make new-workspace NAME=<name>)"
    printf '%s' "$name" | grep -Eq '^[a-z0-9][a-z0-9-]*$' \
        || die "name must be kebab-case: lowercase letters, digits, dashes ('$name')"
    [ "$name" = common ] && die "'common' is reserved for workspaces/common.env"
    local ws="$WS_DIR/$name.env"
    [ -f "$ws" ] && die "$ws already exists — edit it, or pick another name"
    mkdir -p "$WS_DIR"

    # Shared settings live in common.env, written ONCE — seeded from the
    # current .env when there is one (smooth first-time adoption).
    if [ ! -f "$WS_DIR/common.env" ]; then
        {
            echo "# Shared across ALL workspaces — merged first; <name>.env overrides."
            echo "# Same format rules as .env: no '#' or '\$' inside values."
            echo "ENGINE=$(v="$(env_get "$ENV_FILE" ENGINE)"; printf '%s' "${v:-docker}")"
            echo "UID=$(v="$(env_get "$ENV_FILE" UID)"; printf '%s' "${v:-$(id -u)}")"
            echo "GID=$(v="$(env_get "$ENV_FILE" GID)"; printf '%s' "${v:-$(id -g)}")"
            echo "GIT_AUTHOR_NAME=$(env_get "$ENV_FILE" GIT_AUTHOR_NAME)"
            echo "GIT_AUTHOR_EMAIL=$(env_get "$ENV_FILE" GIT_AUTHOR_EMAIL)"
            echo ""
            echo "# Model backend (docs/setup.md, 'Base URL relay'): non-secret"
            echo "# settings only — the API key lives in workspaces/secrets.env."
            echo "ANTHROPIC_BASE_URL=$(env_get "$ENV_FILE" ANTHROPIC_BASE_URL)"
            echo "ANTHROPIC_API_KEY="
            echo "ANTHROPIC_MODEL=$(env_get "$ENV_FILE" ANTHROPIC_MODEL)"
            echo "ANTHROPIC_DEFAULT_HAIKU_MODEL=$(env_get "$ENV_FILE" ANTHROPIC_DEFAULT_HAIKU_MODEL)"
            echo "ANTHROPIC_DEFAULT_SONNET_MODEL=$(env_get "$ENV_FILE" ANTHROPIC_DEFAULT_SONNET_MODEL)"
            echo "ANTHROPIC_DEFAULT_OPUS_MODEL=$(env_get "$ENV_FILE" ANTHROPIC_DEFAULT_OPUS_MODEL)"
        } > "$WS_DIR/common.env"
        echo "Created $WS_DIR/common.env (shared identity/engine — edit once, applies everywhere)."
    fi

    # ANTHROPIC_API_KEY is deliberately NOT seeded from .env: keys belong in
    # the gitignored secrets layer. Warn loudly when a legacy .env holds one.
    if [ -n "$(env_get "$ENV_FILE" ANTHROPIC_API_KEY)" ]; then
        echo "warning: existing .env has ANTHROPIC_API_KEY set — move it into $SECRETS_FILE." >&2
    fi

    # Secrets stub — gitignored from day one (see .gitignore), merged last
    # by switch/new, survives every regeneration of .env.
    if [ ! -f "$SECRETS_FILE" ]; then
        {
            echo "# Secrets merged LAST over every workspace definition."
            echo "# Keep this file out of git (ignored by .gitignore)."
            echo "# Example: your Ollama/Anthropic-compatible relay key —"
            echo "ANTHROPIC_AUTH_TOKEN="
            echo "# (Ollama Cloud needs Bearer auth here; keep ANTHROPIC_API_KEY empty in common.env.)"
        } > "$SECRETS_FILE"
        chmod 600 "$SECRETS_FILE"
        echo "Created $SECRETS_FILE (gitignored) — put your API key(s) there."
    fi

    local seed_pd seed_tc
    seed_pd="$(env_get "$ENV_FILE" PROJECTS_DIR)"
    seed_tc="$(env_get "$ENV_FILE" TOOLCHAINS)"
    cat > "$ws" <<EOF
# Workspace '$name' — applied with: make workspace NAME=$name
# Merged over workspaces/common.env (this file wins on duplicate keys).

# REQUIRED: absolute host path mounted at /workspace (the only writable bind mount).
PROJECTS_DIR=${seed_pd:-/home/you/projects/my-project}

# Comma list of toolchains: php, python, docker (empty = slim runtime).
# Drives BOTH the image contents and the egress allowlist fragments.
TOOLCHAINS=${seed_tc}

# Egress posture:
#   allowlist  — hardened default (curated domains only)
#   learning   — OPEN egress via \`make learn\`: everything logged, signing
#                key removed, doctor red. For research sessions only; pairs
#                best with TOOLCHAINS= (empty).
EGRESS=allowlist

# Optional overrides (defaults come from common.env / compose):
#ANTHROPIC_MODEL=
#MEM_LIMIT=4g
#DIND_MEM_LIMIT=4g
#CPUS=2
#PIDS_LIMIT=512
#NOFILE=4096
#TMP_SIZE=512m
#CERT_DAYS=3

# Extra egress domains for THIS workspace: one squid domain per line in
#   workspaces/$name.allowlist.txt
# (baked into the proxy on switch; 'make denied' shows what got blocked).
#
# For a project REPO, prefer the repo-anchored model instead (config lives
# in the repo, survives machine loss):
#   make add-workspace PROJECT=<path>
EOF
    echo "Created $ws — review/edit it, then activate with:"
    echo "    make workspace NAME=$name"
}

########################################################################
# add <path> [name]  — register a repo-anchored workspace
########################################################################

# kebab-case from a basename; '-' on non-alnum, collapsed and trimmed.
kebab_case() {
    printf '%s' "$1" | tr '[:upper:]' '[:lower:]' \
        | sed -e 's/[^a-z0-9-]\+/-/g' -e 's/-\{2,\}/-/g' -e 's/^-//' -e 's/-$//'
}

# Permissions the installation token may carry; the mint script always sends
# exactly this merged set (never installation-default scope — docs/github.md).
KNOWN_PERMISSIONS="contents pull_requests issues administration workflows deployments actions"

cmd_add() {
    local path="${1:-}" name="${2:-}"
    [ -n "$path" ] || die "usage: make add-workspace PROJECT=~/projects/<name> [WS=<custom-name>]"
    path="${path/#\~/$HOME}"
    [ -d "$path" ] || die "project path '$path' does not exist"
    path="$(cd "$path" && pwd)"
    if ! command -v git >/dev/null 2>&1 \
        || ! git -C "$path" rev-parse --is-inside-work-tree >/dev/null 2>&1; then
        die "'$path' is not a git repo checkout — the repo-anchored model needs one (use new-workspace for local-only)"
    fi

    [ -n "$name" ] || name="$(kebab_case "$(basename "$path")")"
    [ -n "$name" ] || die "could not derive a kebab-case name from '$(basename "$path")' — pass WS=<name>"
    printf '%s' "$name" | grep -Eq '^[a-z0-9][a-z0-9-]*$' \
        || die "name must be kebab-case: lowercase letters, digits, dashes ('$name') — pass WS=<name>"
    [ "$name" = common ] && die "'common' is reserved for workspaces/common.env"
    mkdir -p "$WS_DIR"
    [ -f "$WS_DIR/$name.env" ] && die "$WS_DIR/$name.env already exists — pick another name (WS=<name>)"

    local sc="$path/.secure-container"
    if [ ! -d "$sc" ]; then
        mkdir -p "$sc" "$path/egress"
        # --- profile template -------------------------------------------------
        local toolchains=""
        [ -f "$path/composer.json" ] && toolchains="php"
        { [ -f "$path/docker-compose.yml" ] || [ -f "$path/compose.yaml" ]; } \
            && toolchains="${toolchains:+$toolchains,}docker"
        { [ -f "$path/pyproject.toml" ] || [ -f "$path/requirements.txt" ]; } \
            && toolchains="${toolchains:+$toolchains,}python"
        cat > "$sc/workspace.env" <<EOF
# Repo-anchored profile — COMMITTED to this repo (docs/workspaces.md).
# Merged between workspaces common.env and <name>.env; the generated .env
# inherits it on 'make workspace'. Same format rules as .env: no '# or \$' in values.

# Toolchains (comma list: php, python, docker; empty = slim runtime) —
# drives image contents AND egress registry fragments:
TOOLCHAINS=${toolchains}

# Egress posture: allowlist (hardened default) or learning (open egress,
# logged, signing key removed, NO GitHub scope allowed).
EGRESS=allowlist

# GitHub scope (docs/github.md) — leave commented to stay GitHub-less.
# Requires workspaces/secrets.env: GITHUB_APP_KEY_PATH=<path to the app .pem>.
#GITHUB_APP_ID=
#GITHUB_INSTALLATION_ID=
#GITHUB_REPO=org/name            # comma list for more repos: org/a,org/b
#GITHUB_PERMISSIONS=contents,pull_requests,issues,administration
EOF
        # --- egress allowlist template (the "# why" convention) ---------------
        cat > "$path/egress/allowlist.txt" <<'EOF'
# Per-project egress domains, baked into the sandbox proxy on
# 'make reload-egress'. One squid dstdomain per line; document EACH domain
# with a trailing "# why" — this file is the durable record. Exact host
# beats wildcard ('.api.stripe.com' also matches the apex).
# git remote hosts are NOT allowed here (GITHUB_* scope opens those).

api.example.org   # why: the app's primary API
# .api.stripe.com # why: payment webhooks, if any
EOF
        # --- README ------------------------------------------------------------
        cat > "$sc/README.md" <<EOF
# \`.secure-container/\` — sandbox workspace config

This folder anchors this repo to the hardened Claude Code sandbox
(docs/workspaces.md, docs/github.md). It is committed so the setup travels
with the repo — a fresh machine needs only:

    make add-workspace PROJECT=<this-repo-path>
    make workspace NAME=<name>        # name defaults to the repo basename
    make claude                       # or: make yolo

Contents:

* \`workspace.env\` — the workspace profile (toolchains, egress posture,
  optional GitHub scope).
* \`/egress/allowlist.txt\` (repo root) — per-project egress domains, each
  documented with a \`# why\` comment; the proxy bakes them in on
  \`make reload-egress\`. The in-sandbox agent extends this file at
  \`/workspace/egress/allowlist.txt\` and waits for the host reload.
* This README — what the folder is and how to use it.

Secrets NEVER live here (it is committed): the GitHub App private key path
goes into machine-local \`workspaces/secrets.env\` (\`GITHUB_APP_KEY_PATH=\`).
EOF
        echo "Seeded $sc — REVIEW, ADJUST and COMMIT it in the project repo:"
        echo "    (README.md, workspace.env, egress/allowlist.txt)"
        echo "Add the GitHub App key path to $SECRETS_FILE once a scope is configured:"
        echo "    GITHUB_APP_KEY_PATH=/path/to/app.pem"
    else
        [ -f "$sc/workspace.env" ] || die "$sc exists but has no workspace.env — complete it first (docs/workspaces.md)"
        echo "Found existing $sc — registering a reference, no changes written to the repo."
    fi

    {
        echo "# Workspace '$name' — REFERENCE to the repo-anchored profile at:"
        echo "#   $sc/  (committed in the project repo — edit THERE, not here)"
        echo "# Machine-local overrides only; secrets go into $SECRETS_FILE"
        echo "SECURE_PROJECT_PATH=$path"
        echo "#MEM_LIMIT=4g"
    } > "$WS_DIR/$name.env"

    echo
    echo "Registered workspace '$name' -> $path"
    echo "Activate it with: make workspace NAME=$name"
}

########################################################################
# switch <name>
########################################################################
cmd_switch() {
    local name="${1:-}"
    [ -n "$name" ] || die "usage: scripts/workspace.sh switch <name>  (or: make workspace NAME=<name>)"
    local ws="$WS_DIR/$name.env"
    if [ ! -f "$ws" ]; then
        echo "workspace: no definition $ws" >&2
        cmd_list >&2
        exit 1
    fi

    # --- old state, for the cheapest-apply decision -----------------------
    local old_tc="" old_pd="" old_dind_mem="" was_learning=0 had_env=0
    if [ -f "$ENV_FILE" ]; then
        had_env=1
        old_tc="$(env_get "$ENV_FILE" TOOLCHAINS)"
        old_pd="$(env_get "$ENV_FILE" PROJECTS_DIR)"
        old_dind_mem="$(env_get "$ENV_FILE" DIND_MEM_LIMIT)"
    fi
    [ -e .learning-mode ] && was_learning=1

    # --- guard: never clobber a hand-edited .env --------------------------
    if [ "$had_env" = 1 ]; then
        if grep -q '^# workspace:' "$ENV_FILE"; then
            local stored actual
            stored="$(sed -n 's/^# sha256: //p' "$ENV_FILE" | head -1)"
            actual="$(payload "$ENV_FILE" | sha_of)"
            if [ "$stored" != "$actual" ] && [ "${FORCE:-0}" != 1 ]; then
                die ".env was edited by hand since it was generated.
Fold the edit into $WS_DIR/$(sed -n 's/^# workspace: //p' "$ENV_FILE" | head -1).env (or common.env),
or override once with: FORCE=1 make workspace NAME=$name"
            fi
        else
            # Legacy hand-written .env: preserve it, then take over.
            local backup=.env.pre-workspaces
            [ -e "$backup" ] && backup=".env.pre-workspaces.$$"
            cp "$ENV_FILE" "$backup"
            echo "note: existing hand-written .env preserved as $backup"
        fi
    fi

    # --- merge + validate the new configuration ---------------------------
    local merged new_tc new_pd new_dind_mem new_egress t
    merged="$(merged_for "$name")"
    local tmp
    tmp="$(mktemp)"
    printf '%s\n' "$merged" > "$tmp"
    new_tc="$(env_get "$tmp" TOOLCHAINS)"
    new_pd="$(env_get "$tmp" PROJECTS_DIR)"
    new_dind_mem="$(env_get "$tmp" DIND_MEM_LIMIT)"
    new_egress="$(env_get "$tmp" EGRESS)"
    new_egress="${new_egress:-allowlist}"

    [ -n "$new_pd" ] || die "PROJECTS_DIR is not set in $ws (or common.env, or via SECURE_PROJECT_PATH)"
    [ -d "$new_pd" ] || die "PROJECTS_DIR '$new_pd' does not exist on the host"
    case "$new_egress" in
        allowlist|learning) ;;
        *) die "EGRESS must be 'allowlist' or 'learning' (got '$new_egress')" ;;
    esac
    for t in $(printf '%s' "$new_tc" | tr ',' ' '); do
        [ -f "egress/allowlist.d/$t.txt" ] \
            || die "unknown toolchain '$t' in $ws (no egress/allowlist.d/$t.txt)"
    done

    # Repo-anchored sanity: a declared reference must actually resolve.
    local sp repo_profile
    sp="$(env_get "$WS_DIR/$name.env" SECURE_PROJECT_PATH)"
    repo_profile="$(repo_profile_for "$name")"
    if [ -n "$sp" ] && [ -z "$repo_profile" ]; then
        die "SECURE_PROJECT_PATH '$sp' has no .secure-container/workspace.env — seed it with: make add-workspace PROJECT=$sp"
    fi

    # --- GitHub scope validation (docs/github.md) ------------------------------
    # All-or-nothing: a half-configured scope must not silently disable it.
    # Permissions tokens are validated against the known set; the mint script
    # sends exactly the merged list (never installation-default scope).
    if [ -n "$(env_get "$tmp" GITHUB_APP_ID)" ] || \
       [ -n "$(env_get "$tmp" GITHUB_INSTALLATION_ID)" ] || \
       [ -n "$(env_get "$tmp" GITHUB_REPO)" ]; then
        local gh_repo gh_perms p ok
        for k in GITHUB_APP_ID GITHUB_INSTALLATION_ID GITHUB_REPO; do
            [ -n "$(env_get "$tmp" "$k")" ] || die "incomplete GITHUB scope: $k is missing"
        done
        gh_repo="$(env_get "$tmp" GITHUB_REPO)"
        gh_repo="${gh_repo//,/ }"
        for p in $gh_repo; do
            printf '%s' "$p" | grep -Eq '^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$' \
                || die "GITHUB_REPO entry '$p' is not owner/name"
        done
        gh_perms="$(env_get "$tmp" GITHUB_PERMISSIONS)"
        gh_perms="${gh_perms:-contents,pull_requests,issues,administration}"
        ok=1
        for p in ${gh_perms//,/ }; do
            case " $KNOWN_PERMISSIONS " in *" $p "*) ;; *) ok=0 ;; esac
        done
        [ "$ok" = 1 ] || die "GITHUB_PERMISSIONS has an unknown token (allowed: $KNOWN_PERMISSIONS)"
        # The scope's mint key is a host secret, never committed: it must exist
        # in the machine-local secrets layer.
        [ -n "$(env_get "$SECRETS_FILE" GITHUB_APP_KEY_PATH)" ] \
            || die "GITHUB scope configured but $SECRETS_FILE lacks GITHUB_APP_KEY_PATH=<path-to-app.pem>"
    fi
    if printf '%s\n' "$merged" | grep -q '[#$]'; then
        echo "warning: a value contains '#' or '\$' — Make's .env include mangles both (see Makefile)." >&2
    fi
    # Learning mode and a mounted GitHub token are mutually exclusive: the
    # open proxy would pair with live repo-write access. Refused here (before
    # any state is written) and at the make learn gate itself.
    if scope_active "$tmp" && [ "$new_egress" = learning ]; then
        die "workspace declares EGRESS=learning with a GITHUB scope — never allowed (docs/github.md); drop the GITHUB_* keys from .secure-container/workspace.env or use EGRESS=allowlist"
    fi

    # --- what does the delta require? -------------------------------------
    local build_needed=0 restart_needed=0 frag_changed=0
    local leaving_learning=0 entering_learning=0
    [ "$new_tc" != "$old_tc" ] && build_needed=1
    if [ "$build_needed" = 1 ] || [ "$new_pd" != "$old_pd" ] || [ "$new_dind_mem" != "$old_dind_mem" ]; then
        restart_needed=1
    fi
    if [ "$was_learning" = 1 ] && [ "$new_egress" != learning ]; then leaving_learning=1; fi
    if [ "$was_learning" = 0 ] && [ "$new_egress" = learning ]; then
        entering_learning=1
        # Entering learning mode with toolchains active must be confirmed
        # BEFORE any state is written: otherwise a non-interactive run fails
        # at `make learn` (the gate) with .env already claiming an open
        # posture the marker contradicts (doctor 26 red). With a TTY the
        # gate still asks its own typed-yes.
        if [ -n "$new_tc" ] && [ "${LEARN_ACK:-}" != yes ] && [ ! -t 0 ]; then
            die "workspace declares EGRESS=learning with TOOLCHAINS='$new_tc' but I/O is not a terminal — confirm on the host (interactive switch, or LEARN_ACK=yes)"
        fi
    fi
    local new_frag
    new_frag="$(frag_for "$name")"
    if [ ! -f "$FRAG_TARGET" ] || [ "$new_frag" != "$(cat "$FRAG_TARGET")" ]; then
        frag_changed=1
    fi

    # Git-host scope: materialized only when the merged config declares one.
    local new_scope scope_changed=0
    new_scope="$(git_scope_for "$tmp")"
    if [ ! -f "$SCOPE_TARGET" ] || [ "$new_scope" != "$(cat "$SCOPE_TARGET")" ]; then
        scope_changed=1
    fi

    # Per-project egress: re-merge the project's <repo>/egress/allowlist.txt
    # (PROJECTS_DIR exported for the merge script; it only rewrites on diff)
    # and detect a change like any other fragment. Also reruns after every
    # switch so a git pull that changed .secure-container/ can't go stale.
    local new_project_old project_changed=0
    if [ -f "egress/allowlist.project.txt" ]; then
        new_project_old="$(cat egress/allowlist.project.txt)"
    else
        new_project_old=""
    fi
    PROJECTS_DIR="$new_pd" scripts/merge-project-allowlist.sh 2>&1 \
        || die "merging the project egress allowlist failed (see message above)"
    if [ "$new_project_old" != "$(cat "egress/allowlist.project.txt")" ]; then
        project_changed=1
    fi
    [ "$scope_changed" = 1 ] && frag_changed=1
    [ "$project_changed" = 1 ] && frag_changed=1

    # --- confirm before killing a running session -------------------------
    local eng
    eng="$(engine)"
    if [ "$restart_needed" = 1 ] && [ "${WS_ACK:-}" != yes ] \
        && [ -n "$($eng ps -q -f name='^claude-session$' 2>/dev/null)" ]; then
        echo "A session (claude-session) is RUNNING — the switch needs a restart, which kills it"
        case ",$old_tc," in *,docker,*) echo "and every container nested inside dind (databases, mailpit, ...)." ;; esac
        printf 'Continue? [y/N] '
        local answer=""
        [ -t 0 ] && read -r answer
        case "$answer" in y|Y|yes) ;; *) die "aborted — close the session first, or rerun with WS_ACK=yes" ;; esac
    fi

    # --- write the generated .env + state ---------------------------------
    local sha
    sha="$(printf '%s\n' "$merged" | sha_of)"
    {
        echo "# GENERATED by scripts/workspace.sh from $ws — do not edit."
        echo "# Edit $ws (or workspaces/common.env), then rerun: make workspace NAME=$name"
        echo "# workspace: $name"
        echo "# sha256: $sha"
        printf '%s\n' "$merged"
    } > "$ENV_FILE.tmp"
    mv "$ENV_FILE.tmp" "$ENV_FILE"
    printf '%s\n' "$name" > "$ACTIVE_MARKER"
    printf '%s\n' "$new_frag" > "$FRAG_TARGET"
    printf '%s\n' "$new_scope" > "$SCOPE_TARGET"

    # --- apply ------------------------------------------------------------
    # Order matters: learn-off first (rebuilds the proxy ENFORCING, with the
    # new .env), then image builds, then restart, then learn last (its
    # confirm gate must see the new TOOLCHAINS).
    local running=""
    running="$($eng ps -q --filter label=com.docker.compose.project=claude-sandbox 2>/dev/null | head -1)"

    if [ "$leaving_learning" = 1 ]; then
        echo "--- leaving learning mode (make learn-off) ---"
        make learn-off
    fi
    if [ "$build_needed" = 1 ]; then
        echo "--- toolchains changed ('$old_tc' -> '$new_tc'): make build ---"
        make build
    elif [ "$frag_changed" = 1 ] && [ "$leaving_learning" = 0 ] && [ "$entering_learning" = 0 ]; then
        echo "--- egress fragments changed (workspace/project/scope): make reload-egress ---"
        make reload-egress
    fi
    if [ "$restart_needed" = 1 ] && [ -n "$running" ]; then
        echo "--- applying to running sandbox: make restart ---"
        make restart
    fi
    if [ "$entering_learning" = 1 ]; then
        echo "--- workspace declares EGRESS=learning: make learn ---"
        make learn
    fi

    # --- summary ----------------------------------------------------------
    echo
    echo "Workspace '$name' is active."
    echo "    PROJECTS_DIR = $new_pd"
    echo "    TOOLCHAINS   = ${new_tc:-<none>}"
    echo "    EGRESS       = $new_egress"
    if scope_active "$tmp"; then
        echo "    GITHUB scope = $(env_get "$tmp" GITHUB_REPO)"
        echo "                   (1h tokens; refresh with 'make gh-renew' during long sessions)"
    fi
    if [ "$restart_needed" = 1 ] && [ -z "$running" ]; then
        echo "Nothing was running — start with: make claude   (or make yolo / make shell)"
    fi
    if [ "$build_needed" = 0 ] && [ "$restart_needed" = 0 ]; then
        echo "No rebuild/restart needed — value changes apply to new sessions automatically."
    fi
    [ "$new_egress" = learning ] || echo "Verify the posture with: make doctor"
    rm -f "$tmp"
}

########################################################################
# dispatch
########################################################################
case "${1:-}" in
    list)    cmd_list ;;
    current) cmd_current ;;
    new)     shift; cmd_new "$@" ;;
    add)     shift; cmd_add "$@" ;;
    switch)  shift; cmd_switch "$@" ;;
    *)
        echo "usage: scripts/workspace.sh {list|current|new <name>|add <path> [name]|switch <name>}" >&2
        exit 2
        ;;
esac
