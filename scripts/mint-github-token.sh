#!/usr/bin/env bash
# mint-github-token.sh — mint a short-lived, project-scoped GitHub token for
# the ACTIVE workspace (docs/github.md).
#
# The token is a GitHub App INSTALLATION ACCESS TOKEN: it expires exactly
# 1 h after creation (GitHub-fixed, not configurable) and the mint request
# always narrows the scope — `repositories` = the workspace's GITHUB_REPO
# list, `permissions` = GITHUB_PERMISSIONS (default: contents, pull_requests,
# issues, administration) — never the installation-wide default. This mint
# step is the actual security boundary: it alone decides what any holder of
# the resulting token can touch (the git wrapper is only a stop signal).
#
#   scripts/mint-github-token.sh mint    — consent + mint + write token file
#   scripts/mint-github-token.sh renew   — watch mode: keep fresh while the
#                                          claude-session container runs
#
# Machine inputs:
#   .env            GITHUB_APP_ID / GITHUB_INSTALLATION_ID / GITHUB_REPO /
#                   GITHUB_PERMISSIONS  (generated by `make workspace`)
#   workspaces/secrets.env   GITHUB_APP_KEY_PATH (path to the app .pem, 600)
#
# Consent: every `mint` asks for a typed `yes` (GITHUB_ACK=yes escapes for
# automation). `renew` asks once, then refreshes silently every ~50 min and
# stops itself when the session container is gone.
#
# The private key NEVER leaves WSL and is NEVER mounted into any container;
# only the 1 h token lands in secrets/github-space/token (the file the
# sandbox mounts read-only).
set -euo pipefail

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo_root="$(cd "$script_dir/.." && pwd)"
cd "$repo_root"

TOKEN_FILE=secrets/github-space/token
SECRETS_FILE=workspaces/secrets.env

# Minimal .env reader (quotes stripped, last assignment wins) — same shape
# as scripts/workspace.sh's env_get.
env_get() {
    [ -f "$1" ] || return 0
    sed -n "s/^$2=//p" "$1" | tail -1 \
        | sed -e 's/^"\(.*\)"$/\1/' -e "s/^'\(.*\)'$/\1/"
}

die() { printf 'mint-github-token: %s\n' "$*" >&2; exit 1; }

# Transient/config failures RETURN 1 (renew retries); interactive refusals
# die. Print a `fail=` prefix on the matching line when grepping logs.
fail() { printf 'mint-github-token: %s\n' "$*" >&2; return 1; }

# base64url: RFC 4648 alphabet — '-' replaces '+', '_' replaces '/'.
b64url() { openssl base64 -A | tr '+/' '-_' | tr -d '='; }

# Base64url JWT (RS256) signed with the app private key.
app_jwt() { # app_jwt <key-path> <app-id>
    local key="$1" app_id="$2"
    local header payload now iat exp sig
    now="$(date -u +%s)"
    iat=$((now - 60))
    exp=$((now + 600))
    header='{"alg":"RS256","typ":"JWT"}'
    payload="{\"iat\":$iat,\"exp\":$exp,\"iss\":\"$app_id\"}"
    sig="$(printf '%s.%s' \
        "$(printf '%s' "$header" | b64url)" \
        "$(printf '%s' "$payload" | b64url)" \
        | openssl dgst -sha256 -sign "$key" -binary | openssl base64 -A \
        | tr '+/' '-_' | tr -d '=')"
    printf '%s.%s.%s' \
        "$(printf '%s' "$header" | b64url)" \
        "$(printf '%s' "$payload" | b64url)" \
        "$sig"
}

# permissions map for the mint body: contents,pull_requests,... -> JSON.
permissions_json() { # permissions_json "contents,pull_requests"
    local out="{" first=1 p
    for p in ${1//,/ }; do
        [ "$first" = 1 ] || out="$out,"
        first=0
        out="$out\"$p\":\"write\""
    done
    printf '%s}' "$out"
}

# Throwaway JWT for a given key — proves openssl can sign with it (key
# hygiene, doctor) and lets tests verify the JWT format without GitHub.
cmd_jwt() { # cmd_jwt <key-path> <app-id>
    [ -f "$1" ] || fail "key not found at '$1'" || exit 1
    app_jwt "$1" "$2"
}

mint_once() {
    local app_id inst repos perms key repos_json mode
    app_id="$(env_get .env GITHUB_APP_ID)"
    inst="$(env_get .env GITHUB_INSTALLATION_ID)"
    repos="$(env_get .env GITHUB_REPO)"
    perms="$(env_get .env GITHUB_PERMISSIONS)"
    perms="${perms:-contents,pull_requests,issues,administration}"
    key="$(env_get "$SECRETS_FILE" GITHUB_APP_KEY_PATH)"

    [ -n "$app_id" ] || fail "no GITHUB scope in .env — switch to a scoped workspace first (scc ws switch NAME=<name>)" || return 1
    { [ -n "$inst" ] && [ -n "$repos" ]; } || fail "incomplete GITHUB scope in .env" || return 1
    [ -n "$key" ] || fail "$SECRETS_FILE needs GITHUB_APP_KEY_PATH=<path to the app .pem>" || return 1
    [ -f "$key" ] || fail "app key not found at '$key'" || return 1
    mode="$(stat -c '%a' "$key" 2>/dev/null || true)"
    { [ "$mode" = 600 ] || [ "$mode" = 400 ]; } \
        || fail "app key '$key' has mode $mode — chmod 600 required" || return 1
    head -1 "$key" | grep -q "PRIVATE KEY" || fail "'$key' does not look like a private key (.pem)" || return 1
    if grep -q "ENCRYPTED" "$key"; then
        fail "app key '$key' is passphrase-encrypted — GitHub App keys must be exported unencrypted" || return 1
    fi
    command -v curl >/dev/null || { fail "curl is required to call the GitHub API"; return 1; }
    command -v jq >/dev/null || { fail "jq is required to read the mint response (scripts/preflight.sh installs it)"; return 1; }

    # "repositories" is MANDATORY here: without it the token covers every
    # repo the installation can reach (installation-default scope). The API
    # takes repo NAMES only — the installation already pins the owner — so
    # "acme/keep" from GITHUB_REPO is sent as "keep".
    repos_json="["
    local first=2 r
    for r in ${repos//,/ }; do
        [ "$first" = 2 ] || repos_json="$repos_json,"
        first=0
        repos_json="$repos_json\"${r##*/}\""
    done
    [ "$first" = 0 ] || { fail "GITHUB_REPO is empty — refusing to mint an unscoped token"; return 1; }
    repos_json="$repos_json]"

    local jwt body resp token expires_at
    jwt="$(app_jwt "$key" "$app_id")"
    body="$(printf '{"repositories":%s,"permissions":%s}' "$repos_json" "$(permissions_json "$perms")")"
    resp="$(curl -sS -X POST \
        -H "Authorization: Bearer $jwt" \
        -H "Accept: application/vnd.github+json" \
        -H "X-GitHub-Api-Version: 2022-11-28" \
        "https://api.github.com/app/installations/$inst/access_tokens" \
        -d "$body" -m 30)" || { fail "GitHub API unreachable (curl failed)"; return 1; }

    if printf '%s' "$resp" | grep -q '^{"message":'; then
        fail "GitHub refused the mint ($(printf '%s' "$resp" | head -1 | cut -c1-200)) — check GITHUB_APP_ID / GITHUB_INSTALLATION_ID / key"; return 1
    fi
    token="$(printf '%s' "$resp" | jq -er '.token')" \
        || { fail "unexpected mint response: $(printf '%s' "$resp" | head -1 | cut -c1-200)"; return 1; }
    expires_at="$(printf '%s' "$resp" | jq -r '.expires_at')"

    umask 077
    printf '%s' "$token" > "$TOKEN_FILE.tmp.$$"
    mv "$TOKEN_FILE.tmp.$$" "$TOKEN_FILE"
    echo "Token minted for ${repos} (${perms}) — expires_at: $expires_at"
    echo "Wrote $TOKEN_FILE (mode 600, mounted read-only into the sandbox)."
}

consent() {
    local repos perms
    repos="$(env_get .env GITHUB_REPO)"
    perms="$(env_get .env GITHUB_PERMISSIONS)"
    perms="${perms:-contents,pull_requests,issues,administration}"
    if [ "${GITHUB_ACK:-}" = yes ]; then
        echo "mint-github-token: GITHUB_ACK=yes — proceeding non-interactively."
        return 0
    fi
    cat >&2 <<EOF

┌─ MINT GITHUB TOKEN — CONFIRM ─────────────────────────
│ Workspace scope (from .secure-container/workspace.env):
│   repositories: $repos
│   permissions:  $perms
│   lifetime:     1 hour (auto-refreshed by 'make gh-renew')
│
│ A hostile session could use this token to push, open
│ PRs/issues, and merge in the repos above — for one hour.
│ Scope is enforced at MINT time; the git wrapper in the
│ sandbox is advisory only.
│
│ Type 'yes' to mint.
└───────────────────────────────────────────────────────
EOF
    if [ ! -t 0 ]; then
        die "not a terminal — set GITHUB_ACK=yes for automation"
    fi
    local answer=""
    printf 'Type yes: ' >&2
    read -r answer
    [ "$answer" = yes ] || die "aborted — nothing minted"
}

session_running() {
    local eng
    eng="$(env_get .env ENGINE)"
    eng="${eng:-docker}"
    [ -n "$("$eng" ps -q -f name='^claude-session$' 2>/dev/null)" ]
}

cmd="${1:-}"
case "$cmd" in
    jwt)   shift; cmd_jwt "$@" ;;
    mint)
        consent
        mkdir -p secrets/github-space
        mint_once || exit 1
        ;;
    renew)
        consent
        mkdir -p secrets/github-space
        echo "gh-renew: refreshing the token every ~50 min while the session runs."
        echo "          Stop with Ctrl-C; stops itself when claude-session is gone."
        session_running || die "no claude-session container is running — start the session first (scc claude / scc yolo)"
        mint_once || exit 1
        while session_running; do
            interval=3000
            echo "gh-renew: sleeping ${interval}s — $(date '+%H:%M:%S')"
            sleep "$interval" || true
            session_running || break
            mint_once || { echo "gh-renew: mint failed — retrying in 60s" >&2; sleep 60; }
        done
        echo "gh-renew: session gone — stopped. The last token expires within an hour."
        ;;
    *)
        echo "usage: scripts/mint-github-token.sh {mint|renew|jwt <key> <app-id>}
  make gh-token   — one-shot mint + hand to \`gh auth login --with-token\`
  make gh-renew   — keep a session supplied with fresh tokens
  jwt             — emit a throwaway JWT (key hygiene checks; never sent)" >&2
        exit 2
        ;;
esac
